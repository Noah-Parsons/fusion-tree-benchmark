"""rmi_registry.py — writes data/rmi/registry.cpp from the RMI manifest.

The manifest (data/rmi/manifest.csv, written by analysis/rmi_grid.py) lists
every generated RMI: namespace, dataset, seed, rank, layers, branching
factor. For each one this reads the fingerprint of the keys it was trained on
(key count, first key, last key) straight from the dump file, so RMIIndex can
match an RMI to the keys it is given without being told the dataset or seed.

Run from the repository root:  python analysis/rmi_registry.py
"""
import csv
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RMI = ROOT / "data" / "rmi"
GEN = RMI / "gen"
SAMPLES = ROOT / "data" / "samples"


def fingerprint(path: Path):
    """(count, first, last, key at n/4, key at n/2). The two interior keys were added on
    2026-10-19: the wiki samples for seeds 20260910 and 20260912 share count, first and last key,
    so the registry matched seed 12's keys to seed 10's RMI."""
    def key_at(f, i):
        f.seek(8 + 8 * i)
        return struct.unpack("<Q", f.read(8))[0]
    with open(path, "rb") as f:
        (n,) = struct.unpack("<Q", f.read(8))
        return n, key_at(f, 0), key_at(f, n - 1), key_at(f, n // 4), key_at(f, n // 2)


def main():
    rows = list(csv.DictReader(open(RMI / "manifest.csv", newline="")))
    rows = [r for r in rows if (GEN / f"{r['namespace']}.h").exists()]
    missing = [r["namespace"] for r in csv.DictReader(open(RMI / "manifest.csv", newline=""))
               if not (GEN / f"{r['namespace']}.h").exists()]
    prints = {}
    lines = [
        "// registry.cpp — GENERATED by analysis/rmi_registry.py. Do not edit.",
        '#include "rmi_index.hpp"',
    ]
    lines += [f'#include "{r["namespace"]}.h"' for r in rows]
    lines += ["", "namespace ft {", "static const RMIEntry kEntries[] = {"]
    for r in rows:
        key = (r["dataset"], r["seed"])
        if key not in prints:
            prints[key] = fingerprint(SAMPLES / f"{r['dataset']}_{r['seed']}")
        n, first, last, q1, mid = prints[key]
        ns = r["namespace"]
        arch = f"{r['layers']} {r['branching']}"
        lines.append(
            f'    {{"{r["dataset"]}", {r["seed"]}ULL, {r["rank"]}, "{arch}", {n}ULL, {first}ULL, {last}ULL, '
            f"{q1}ULL, {mid}ULL, &{ns}::load, &{ns}::cleanup, &{ns}::lookup, {ns}::RMI_SIZE}},"
        )
    # Two different key sets must never share a fingerprint, or an RMI is used on the wrong keys.
    seen = {}
    for key, fp in prints.items():
        if fp in seen and seen[fp] != key:
            raise SystemExit(f"fingerprint collision between {seen[fp]} and {key}: {fp}")
        seen[fp] = key
    if not rows:
        lines.append('    {"", 0, 0, "", 0, 0, 0, 0, 0, nullptr, nullptr, nullptr, 0},')
    lines += [
        "};",
        "const RMIEntry* rmi_registry(std::size_t& count) {",
        f"    count = {len(rows)};",
        "    return kEntries;",
        "}",
        'const char* rmi_data_path() { return "data/rmi/params"; }',
        "} // namespace ft",
        "",
    ]
    (RMI / "registry.cpp").write_text("\n".join(lines), newline="\n")
    print(f"registry: {len(rows)} RMIs" + (f"; missing generated code for {len(missing)}: {missing}" if missing else ""))


if __name__ == "__main__":
    main()
